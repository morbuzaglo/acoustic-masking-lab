def f1(v):
    return '—' if v is None else f'{v:.1f}'


def ch8(b, D):
    b.chapter('חיזוי ואופטימיזציה: תרחיש לדוגמה', 'ch8')
    sc = D['scn']['hammer']
    b.para(f'התרחיש הוא **הכאה סינתטית** של 4 s ב-60 dBA במקלט, עם רמת שיא של {sc["target_Lpeak"]:.0f} dB (גורם שיא של כ-{sc["target_Lpeak"] - sc["target_LAeq"]:.0f} dB), '
           'מול תשעה מסכים. הנתונים סינתטיים, ולכן המטרה כאן היא להדגים את המערכת ואת סוג המסקנות שהיא מאפשרת, לא להסיק על רעש ממשי.')
    b.section('הגדרות')
    b.bullets([
        '**קריטריון גילוי**: $P_{\\mathrm{crit}}$ של 2AFC. $P=0.5$ הוא ניחוש, $0.75$ הוא סף מקובל, ו-$0.6$ (כלומר $d\'=0.36$) הוא "קרוב מאוד לניחוש". השתמשנו ב-0.6 וב-0.75.',
        '**רמה נדרשת**: LAeq של המסכה במקלט שבה ההסתברות המנובאת שווה לקריטריון. הסצנה כולה מוגדלת או מוקטנת.',
        '**SNR**: LAeq של קטע המטרה פחות LAeq של המסכה, שניהם פיזיקליים במקלט.',
        '**אי-ודאות**: סטיית תקן בין שלושה מימושי רעש (בסצנות אקראיות) מחוברת בריבוע ל-3 dB של אי-ודאות המודל; הטווח המוצג הוא ‎±1.96 סטיות תקן.',
    ])
    b.section('הרמה הנדרשת')
    rows = sorted(sc['criteria']['0.6'], key=lambda r: (r['required_masker_LAeq'] is None, r['required_masker_LAeq'] or 0))
    ok = [r for r in rows if r['required_masker_LAeq'] is not None]
    best = ok[0]
    b.para(f'{{ref:fig_levels}} מציג את הרמה הנדרשת בשני הקריטריונים. המסכה הטובה ביותר היא **{HEBN.get(best["name"], best["name"])}** ב-{best["required_masker_LAeq"]:.1f} dBA, והיא גבוהה ב-{best["required_masker_LAeq"] - sc["target_LAeq"]:.0f} dB מה-LAeq של הרעש עצמו. '
           'המסקנה הפרקטית: **כשהרעש אימפולסיבי, הרמה הנדרשת נקבעת על ידי השיאים**. כל קטע בן כמה אלפיות שנייה מעל הרקע מספיק כדי שהמאזין יזהה את הרעש, ולכן LAeq אינו מדד מתאים לתכנון המסכה.')
    b.fig(FIG / 'scenario' / 'fig_required_levels', 'רמת מסכה נדרשת במקלט (dBA) להכאה סינתטית של 60 dBA, בשני קריטריוני גילוי. הקו המקווקו הוא ה-LAeq של המטרה; פסי השגיאה הם טווח של 95% של המודל.', 'fig_levels')
    t = []
    for r in rows:
        m = r.get('metrics') or {}
        u = r['uncertainty']
        if r['required_masker_LAeq'] is None:
            t.append([HEBN.get(r['name'], r['name']), CATH.get(r['category'], r['category']), 'לא ניתן להשגה', '—', '—', '—', '—'])
            continue
        t.append([HEBN.get(r['name'], r['name']), CATH.get(r['category'], r['category']), f1(r['required_masker_LAeq']), f'{f1(u["lo95"])} … {f1(u["hi95"])}', f1(r['snr_at_threshold']), f1(m.get('N5_sone')), f1(m.get('PA_proxy'))])
    b.table(['מסכה', 'סוג', 'LAeq נדרש', 'טווח 95%', 'SNR', 'N5', 'PA'], t, caption='רמה נדרשת לקריטריון P=0.6, ואומדני עוצמה ומטרד יחסיים (N5 ב-sone ו-PA, יחסיים בלבד)', label='tab_levels',
            widths=[3.6, 2.0, 2.4, 3.4, 1.6, 1.6, 1.6])
    bad = [r for r in rows if r['required_masker_LAeq'] is None]
    if bad:
        b.para('**שלושה מסכים אינם מסוגלים להסתיר את המטרה בשום רמה** שבדקנו (עד 80 dB מעל הרמה ההתחלתית, כלומר כ-120 dBA): ' + ', '.join(HEBN.get(r['name'], r['name']) for r in bad) + '. '
               'הם חסרי אנרגיה מתחת ל-1–2 kHz, והמטרה כוללת "חבטה" נמוכה סביב 160 Hz ותהודה ב-1.25 kHz שנשארות מעל הסף. זו מסקנה חשובה לתכנון: מסכה צרת סרט בתדרים גבוהים לא תסתיר רעש רחב סרט, גם ברמה גבוהה מאוד. '
               'המערכת מדווחת מצב זה במפורש ("not reachable") ולא כמספר.')
    nat = [r for r in ok if r['category'] == 'natural']
    syn = [r for r in ok if r['category'] == 'synthetic']
    if nat and syn:
        b.para(f'ההשוואה בין טבעי לסינתטי ברורה: המסכה הטבעית הטובה ביותר דורשת {nat[0]["required_masker_LAeq"]:.1f} dBA, והסינתטית הטובה ביותר {syn[0]["required_masker_LAeq"]:.1f} dBA. '
               'הסיבה היא ספקטרלית. רוח ומים מרוכזים בתדרים נמוכים ובינוניים, והרעש התעשייתי הסינתטי בנוי מתהודות בין 1.2 ל-6.9 kHz. ברעש ורוד יש הספק שווה לכל אוקטבה, ולכן הוא מכסה את התדרים האלה בצורה יעילה יותר לכל dBA מוסף. '
               'עם זאת, ב-dBA הוא גם הכי "קשה" לשמיעה כשלעצמו, ולכן הדוח מציג את מדדי העוצמה והמטרד בנפרד.')
    b.section('עקומות גילוי ומפת הסוואה')
    b.para('{ref:fig_curves} מציג את הגילוי כפונקציה של רמת המסכה. המעבר מ-1.0 ל-0.5 נמשך כ-20 עד 25 dB, הרבה יותר מהמעבר בטון ברעש (כ-12 dB), כי המטרה רחבת סרט ומורכבת מפגיעות חוזרות. שגיאה של כמה dB ברמה הנדרשת משנה את ההסתברות במידה מתונה. '
           '{ref:fig_map} מראה **איפה** מתרחש הגילוי: כל תא מציג את יחס המטרה לרעש (מסכה ועוד רצפה פנימית) בערוץ ובמסגרת זמן. התאים הבהירים הם ההתרחשויות של הכאות בתדרים הבינוניים והגבוהים, והם אלה שהמסכה חייבת לכסות.')
    b.fig(FIG / 'scenario' / 'fig_detection_curves', 'גילוי ההכאה כפונקציה של רמת המסכה, לשישה מסכים. הקו המקווקו הוא קריטריון P=0.6.', 'fig_curves')
    b.fig(FIG / 'scenario' / 'fig_masking_map', 'מפת הסוואה: יחס מטרה למסכה בכל תא זמן-תדר, מסכה ורודה ב-40 dBA. הכאות חוזרות נראות כפסים אנכיים.', 'fig_map')
    b.section('אופטימיזציה של צורת הספקטרום')
    b.para('הרחבנו את הבעיה לבחירת צורת הספקטרום. המשתנים הם 12 הגברות (dB) לרצועות על ציר לוג התדר, בין 100 Hz ל-10 kHz, בחלוקה שבה סכום ריבועי המשקולות הוא אחד (power-complementary), כך שהספק הערוץ של המסכה המעוצבת הוא סכום חזקות מדויק: ' )
    b.eq(r'E_k(t)=\sum_{j=1}^{12}g_j^2\,E_{b,j}(k,t)', 'eq_bands')
    b.para('ה-$E_{b,j}$ מחושבים פעם אחת, והאופטימיזציה אינה דורשת סינון חוזר. הבעיה היא:')
    b.eq(r'\min_{\mathbf g}\;L_{A}(\mathbf g)+\lambda\cdot10\lg\frac{N(\mathbf g)}{1\,\mathrm{sone}}\quad\mathrm{s.t.}\quad P_{2AFC}(\mathbf g)\le P_{\mathrm{crit}}', 'eq_opt')
    b.para('פתרנו אותה ב-SLSQP עם צעד הפרשים של 0.4 dB (נדרש בגלל אי-חלקות של מקסימום החלון והסוואה לאחור) ועם כיוונון אחרון של הגברה אחידה שמחזיר את האילוץ בדיוק. '
           'המטרה הראשונה היא LAeq המוסף, והשנייה היא פרוקסי העוצמה $N$; מדד המטרד אינו נכנס לפונקציית המטרה, אלא מדווח.')
    opt = [r for r in rows if r.get('optimised')]
    if opt:
        txt = '; '.join(f'{HEBN.get(r["name"], r["name"])}: {r["required_masker_LAeq"]:.1f} לפני ו-{r["optimised"]["LAeq"]:.1f} אחרי' for r in opt)
        sav = [r['required_masker_LAeq'] - r['optimised']['LAeq'] for r in opt]
        b.para(f'התוצאות ({txt}) מראות שהחיסכון תלוי מאוד במסכה. עבור רעש ורוד, שכבר קרוב לצורה הנכונה, החיסכון קטן (כ-{min(sav):.1f} dB). '
               f'עבור מסכים טבעיים החיסכון עצום (עד {max(sav):.0f} dB), כי האופטימיזציה מדכאת את הרצועות שאינן תורמות לגילוי ומעצימה את התדרים הגבוהים שבהם נמצאות תהודות המטרה. '
               'לאחר האופטימיזציה כל שלושת המסכים מגיעים לטווח צר של רמות (כ-85.5 עד 86.6 dBA). זו תוצאה של המודל על מטרה סינתטית, ולא המלצה: הספקטרום המותאם רחוק מאוד מצליל טבעי (ההגברות נעות בטווח של עשרות dB), ולכן הוא עשוי לאבד בדיוק את היתרון הטבעי שבשבילו נבחר. '
               'מעבר לכך הפרוקסי של העוצמה ירד מאוד (מכ-97 ל-72 sone ברעש ורוד), מה שמראה שאין התנגשות בין מזעור dBA לבין מזעור עוצמה במקרה זה.')
        b.fig(FIG / 'scenario' / 'fig_optimised', 'הספקטרום המותאם: חיסכון ברמה (משמאל) והגברת כל רצועה בתרחיש הראשון (מימין).', 'fig_opt')
    b.section('מה לא ניתן להסיק מהתרחיש')
    b.bullets([
        'המטרה והמסכים סינתטיים, ולכן המספרים אינם נתוני שדה.',
        'החיזוי הוא לגילוי אנרגטי של מטרה ידועה. מאזין שאינו יודע מה לחפש עשוי להיות פחות רגיש, ומאזין מנוסה אולי יותר.',
        'LAeq גבוה של מסכה עשוי להיות לא מקובל בפני עצמו. מצאנו שהרמות הנדרשות להסתרת שיאים של 88 dB גבוהות מרמת הרעש עצמו, ולכן מסכה אינה תחליף להפחתה במקור כשהרעש אימפולסיבי.',
    ])


